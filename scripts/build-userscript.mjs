import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const read = (path) => readFile(new URL(path, root), 'utf8');
const manifest = JSON.parse(await read('extension/manifest.json'));
let core = (await read('extension/page.js')).trimEnd();
const settings = (await read('userscript/settings.js')).trimEnd();
const license = (await read('LICENSE')).trimEnd();
const upstream = (await read('extension/THIRD_PARTY_NOTICES.md')).trimEnd();

function replaceOnce(source, before, after) {
  if (source.split(before).length !== 2) {
    throw new Error(`Shared comment integration changed: expected one ${before}`);
  }
  return source.replace(before, after);
}

// Share the audited component integration while keeping each distribution's
// labels and preferences independent when both are accidentally enabled.
core = replaceOnce(core,
  "const MARKER = 'data-bili-ip-lens';",
  "const MARKER = 'data-bili-ip-lens-userscript';");
for (const event of ['settings', 'status', 'ready', 'request-status']) {
  core = replaceOnce(core, `'bili-ip-lens:${event}'`, `'bili-ip-lens-userscript:${event}'`);
}
core = replaceOnce(core,
  "root.querySelector('#location, .reply-location, [data-ip-location]')",
  "root.querySelector('#location, .reply-location, [data-ip-location], [data-bili-ip-lens]')");

const header = `// ==UserScript==
// @name         Bili IP Lens · B站评论 IP 属地
// @name:en      Bili IP Lens · Bilibili Comment IP Region
// @namespace    https://github.com/8TrafficAI/bili-ip-lens
// @version      ${manifest.version}
// @description  显示 B站评论已有的 IP 属地，油猴菜单一键开关并保存设置；不额外查询 IP，不上传评论数据。
// @description:en Show the IP region already supplied with Bilibili comments. Toggle instantly from the userscript menu with a saved preference. No IP lookup or data upload.
// @author       8TrafficAI contributors
// @copyright    2026 Bili IP Lens contributors; 2023-present MaxChang3
// @license      MIT
// @homepageURL  https://github.com/8TrafficAI/bili-ip-lens
// @supportURL   https://github.com/8TrafficAI/bili-ip-lens/issues
// @match        https://www.bilibili.com/*
// @match        https://t.bilibili.com/*
// @match        https://space.bilibili.com/*
// @run-at       document-start
// @noframes
// @sandbox      JavaScript
// @grant        unsafeWindow
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_registerMenuCommand
// @grant        GM_unregisterMenuCommand
// @grant        GM_addValueChangeListener
// ==/UserScript==`;

const output = `${header}

/*
Generated by scripts/build-userscript.mjs; edit extension/page.js or
userscript/settings.js and rebuild. All functional code is included here.
No external script is downloaded or injected. Update checks are left to the
userscript manager, using the source from which the user installs this file.

${license}

${upstream}
*/

(() => {
  'use strict';
  // Use the page's objects rather than sandbox DOM wrappers so component.data
  // and customElements refer to Bilibili's actual JavaScript objects.
  const page = unsafeWindow;
  const document = page.document;
  const customElements = page.customElements;
  const CustomEvent = page.CustomEvent;
  const Event = page.Event;
  const queueMicrotask = page.queueMicrotask.bind(page);

${core}

${settings}
})();
`;

const destination = new URL('userscript/bili-ip-lens.user.js', root);
if (process.argv.includes('--check')) {
  let current = '';
  try { current = await readFile(destination, 'utf8'); } catch {}
  if (current !== output) {
    throw new Error('Userscript is stale. Run node scripts/build-userscript.mjs.');
  }
  console.log('Generated userscript matches its shared component source and manifest.');
} else {
  await mkdir(new URL('userscript/', root), { recursive: true });
  await writeFile(destination, output);
  console.log(destination.pathname);
}
